export function getAllLessonsFlat() {
  return curriculum.flatMap((courseModule) =>
    courseModule.lessons.map((lesson) => ({
      ...lesson,
      moduleSlug: courseModule.slug,
      moduleTitle: courseModule.title,
      moduleOrder: courseModule.order,
    }))
  );
}

export function getModuleBySlug(moduleSlug) {
  return curriculum.find((courseModule) => courseModule.slug === moduleSlug) ?? null;
}

export function getLesson(moduleSlug, lessonSlug) {
  const courseModule = getModuleBySlug(moduleSlug);
  if (!courseModule) return null;
  const lesson = courseModule.lessons.find((l) => l.slug === lessonSlug);
  if (!lesson) return null;
  return { module: courseModule, lesson };
}

export function getAdjacentLessons(moduleSlug, lessonSlug) {
  const flat = getAllLessonsFlat();
  const index = flat.findIndex(
    (l) => l.moduleSlug === moduleSlug && l.slug === lessonSlug
  );
  if (index === -1) return { previous: null, next: null };
  return {
    previous: index > 0 ? flat[index - 1] : null,
    next: index < flat.length - 1 ? flat[index + 1] : null,
  };
}

export const totalLessonCount = curriculum.reduce(
  (sum, courseModule) => sum + courseModule.lessons.length,
  0
);
